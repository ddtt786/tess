// ============================================================================
//  함수 매개변수 이름 규칙 — 컴파일러와 되돌리기가 공유한다
//
//  엔트리 함수의 머리 부분은 라벨(글자)과 매개변수 칸이 번갈아 나올 수 있는 사슬이다.
//  예를 들어 `스폰 (인수) 체력 (인수)` 는 라벨-인수-라벨-인수 네 마디로 되어 있다.
//  Tess 의 `function 이름(a, b)` 에는 그런 마디가 없으므로, 그 정보를 매개변수 이름에 담는다.
//
//    라벨-인수-인수      ->  이름(a, b)          맨 앞 라벨만 함수 이름
//    라벨-인수-라벨-인수  ->  이름(a, 체력)        중간 라벨은 바로 뒤 인수의 이름이 된다
//    라벨-인수-라벨      ->  이름(a)             뒤에 인수가 없는 라벨은 살릴 자리가 없다
//
//  즉 제자리에 있는 자동 이름(a, b, c … z, a1, a2 …)은 라벨 없는 매개변수를 뜻하고,
//  그 밖의 이름은 그 이름을 라벨로 단 매개변수를 뜻한다. 컴파일할 때도 이 규칙을
//  그대로 뒤집어 쓰므로(buildFunctionFields), 되돌린 함수는 원래 모양으로 돌아오고
//  직접 적은 `function 스폰(a, 체력)` 도 엔트리에서 `스폰 (인수) 체력 (인수)` 로 보인다.
// ============================================================================
const LETTERS = 'abcdefghijklmnopqrstuvwxyz';

/** 라벨이 없는 i 번째(0부터 센다) 매개변수의 자동 이름: a, b, … z, a1, a2, … */
export function autoParamName(index) {
  return index < LETTERS.length ? LETTERS[index] : `a${index - LETTERS.length + 1}`;
}

/** 이 이름이 그 자리의 자동 이름과 같은지 확인한다. 같으면 라벨이 없는 매개변수이다. */
export function isAutoParamName(name, index) {
  return name === autoParamName(index);
}
